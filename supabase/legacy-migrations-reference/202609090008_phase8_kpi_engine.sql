create table kpi_definitions(id uuid primary key default gen_random_uuid(),organization_id uuid not null references organizations(id),code text not null,name text not null,category text not null default 'OPERATIONS',unit text not null default 'UNITS',direction text not null default 'LOWER_IS_BETTER' check(direction in('HIGHER_IS_BETTER','LOWER_IS_BETTER','TARGET_RANGE')),frequency text not null default 'REALTIME',data_source text,data_readiness_status text not null check(data_readiness_status in('ACTIVE','WAITING_FOR_DATA','DISABLED')),is_active boolean not null default false,dashboard_priority integer,owner_role text not null default 'manager',supports_area_dimension boolean not null default false,created_at timestamptz not null default now(),updated_at timestamptz not null default now(),unique(organization_id,code));
create table kpi_targets(id uuid primary key default gen_random_uuid(),organization_id uuid not null references organizations(id),kpi_definition_id uuid not null references kpi_definitions(id),production_area_id uuid references production_areas(id),shift_id uuid references shift_templates(id),effective_from date not null,effective_to date,target_value numeric not null,warning_value numeric,critical_value numeric,created_by uuid,created_at timestamptz not null default now(),updated_at timestamptz not null default now(),check(effective_to is null or effective_to>=effective_from));
create table kpi_results(id uuid primary key default gen_random_uuid(),organization_id uuid not null references organizations(id),kpi_definition_id uuid not null references kpi_definitions(id),period_start timestamptz not null,period_end timestamptz not null,production_date date not null,production_area_id uuid references production_areas(id),shift_id uuid references shift_templates(id),machine_id text,operator_id text,order_no text,product_code text,numerator numeric,denominator numeric,value numeric,target_value numeric,status text not null check(status in('GOOD','WARNING','CRITICAL','NO_TARGET','NO_DATA')),data_quality_status text not null check(data_quality_status in('NO_DATA','PARTIAL_DATA','STALE_DATA','VALID')),source_refresh_at timestamptz,calculated_at timestamptz not null default now());
create index kpi_results_latest_idx on kpi_results(organization_id,kpi_definition_id,calculated_at desc);create index kpi_targets_effective_idx on kpi_targets(organization_id,kpi_definition_id,effective_from desc);
alter table kpi_definitions enable row level security;alter table kpi_targets enable row level security;alter table kpi_results enable row level security;revoke all on kpi_definitions,kpi_targets,kpi_results from anon,authenticated;grant select,insert,update,delete on kpi_definitions,kpi_targets to service_role;grant select,insert on kpi_results to service_role;

